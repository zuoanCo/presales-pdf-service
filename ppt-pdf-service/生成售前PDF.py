BASE_DIR = Path(__file__).resolve().parent
TEMPLATE = BASE_DIR / "templates" / "售前模板.pptx"
OUTPUT_DIR = BASE_DIR / "output"
OUTPUT_DIR.mkdir(exist_ok=True)


def main() -> None:
    filled_pptx = OUTPUT_DIR / "售前诊断建议书.pptx"
    pdf_path = OUTPUT_DIR / "售前诊断建议书.pdf"

    # 1. 填充参数（空字符串的参数会保留 {{占位符}} 原样并提示）
    active = {k: v for k, v in PARAMS.items() if v != ""}
    missing = load_and_fill(str(TEMPLATE), active, str(filled_pptx))
    if missing:
        print(f"[提示] 以下参数未填，PDF 中保留占位符: {missing}")

    # 2. 转成 PDF（保真度 100%，就是 PowerPoint 自己的渲染）
    backend = convert(str(filled_pptx), str(pdf_path))
    print(f"[完成] {pdf_path}  （转换后端: {backend}）")


if __name__ == "__main__":
    main()
